# 設定聖誕樹的高度；數字 6 代表樹冠總共有 6 層。
height = 6

# 外層迴圈負責一層一層地畫出聖誕樹。
# range(height) 會產生 0、1、2、3、4、5，因此 row 會從 0 開始，共執行 6 次。
# row 代表目前正在畫第幾層；程式從 0 開始計數，所以 row=0 是第 1 層。
for row in range(height):
    # 先印出每一層星號前面的空白，讓聖誕樹保持置中。
    # 空白數量的公式是 height - row - 1：
    # 第 1 層有 5 個空白，之後每往下一層就少 1 個空白。
    for space in range(height - row - 1):
        # 每次印出 1 個空白。
        # end="" 表示印完後不要換行，讓下一個空白或星號接在同一行後面。
        print(" ", end="")

    # 接著印出目前這一層的星號。
    # 星號數量的公式是 2 * row + 1，所以每一層都是奇數個星號：1、3、5、7、9、11。
    for star in range(2 * row + 1):
        # 每次印出 1 個星號，同樣使用 end=""，讓所有星號排在同一行。
        print("*", end="")

    # 這個 print() 沒有要印的內容，所以只會換行。
    # 換行後，外層迴圈就會開始畫下一層聖誕樹。
    print()
